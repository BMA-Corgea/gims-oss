def _is_valid_date(val: str, fmt: str = "yyyy-mm-dd") -> bool:
    from datetime import datetime as _dt
    try:
        _dt.strptime(val.strip(), "%Y-%m-%d")
        return True
    except Exception:
        return False

def _list_ids_for_noun(project_path: Path, project: str, noun_name: str, pid_field: str) -> List[str]:
    """
    Return list of primary IDs for a noun, always from DB (RDS or SQLite).
    """
    schema = get_noun_schema(project_path, noun_name) or {}
    primary = pid_field or schema.get("primary_id_field") or "id"
    from core.storage.factory import collection_for_noun, get_record_store
    rows = get_record_store(project_path).list_records(collection_for_noun(noun_name))
    return [str(r.get(primary)) for r in rows if r.get(primary) not in (None, "")]

def validate_item_against_schema(item: dict, noun_name: str, schema: dict, project_path: Path, project: Optional[str] = None) -> List[str]:
    """
    Validate a single item dict against the noun schema.

    Thin adapter over the ONE validation engine (``core.words.validation.validate_instance``):
    adjective fields are resolved against the RDS-aware adjective schema and references resolve
    against the SQL store via :class:`SqlIdProvider` (so editor + workbench + audit resolve
    references through one engine). Legacy error wording is preserved.

    Behavior preserved: a blank *primary* field is allowed (it arrives via the path on update).
    Behavior change (intentional, a bug fix): date fields are now validated against their
    declared format (the old ``_is_valid_date`` ignored ``format`` and only accepted ISO).
    ISO is still accepted as a fallback, so no previously-stored value is newly rejected.
    """
    from core.words.resolve import resolve_noun_wordtype
    from core.words.id_provider import SqlIdProvider
    from core.words.validation import validate_instance, render_legacy_errors

    def _get_adj(field: str):
        return get_adjective_schema(project_path, field, applies_to=noun_name) or None

    wt = resolve_noun_wordtype(noun_name, schema, _get_adj)

    def _sql_list_ids(ref_noun: str):
        ref_schema = get_noun_schema(project_path, ref_noun)
        if not ref_schema:
            return []
        ref_primary = ref_schema.get("primary_id_field")
        if not ref_primary:
            return []
        return _list_ids_for_noun(project_path, project or "", ref_noun, ref_primary)

    norm = {k: (v.strip() if isinstance(v, str) else v) for k, v in (item or {}).items()}
    findings = validate_instance(norm, wt, SqlIdProvider(_sql_list_ids))

    primary_field = (schema or {}).get("primary_id_field")
    findings = [f for f in findings
                if not (f.code == "REQUIRED_FIELD_MISSING" and f.field == primary_field)]
    return render_legacy_errors(findings, wt)

# ──────────────────────────────────────────────────────────────────────────────
# Autogen helpers
# ──────────────────────────────────────────────────────────────────────────────
def _autogen_enforced_blank(schema: dict, payload: Dict[str, Any], mode: str) -> Optional[str]:
    """If autogenerate_id and create mode, primary must be blank."""
    if mode != "create":
        return None
    if not schema.get("autogenerate_id"):
        return None
    p = schema.get("primary_id_field")
    if p and payload.get(p):
        return f"Field '{p}' must be blank (autogenerated)."
    return None

def _generate_primary(schema: dict, noun_type: str, project_path: Path, existing_ids: Optional[List[str]] = None) -> str:
    """Generate primary with core/id_generator.py; fallback to timestamp on error."""
    from datetime import datetime as _dt
    primary = schema.get("primary_id_field")
    if not primary:
        raise AppError("SCHEMA_MISSING_PRIMARY_ID", "Schema missing primary_id_field.", status=400, details={"noun_type": noun_type})
    try:
        noun_types_path = project_path / "noun_types.json"
        return generate_autogenerated_id(
            noun_type_name=noun_type,
            noun_schema=schema,
            noun_types_path=noun_types_path,
            existing_ids=set(existing_ids or []),
        )
    except Exception as e:
        log.debug("[autogen] generator error; fallback", e)
        return f"{noun_type[:4].upper()}-{_dt.utcnow().strftime('%Y%m%d%H%M%S%f')[-10:]}"
