# Backend selection (SQLite offline vs RDS Postgres)
# ──────────────────────────────────────────────────────────────────────────────
def _normalize_for_psycopg(url: str) -> str:
    """
    Convert SQLAlchemy/async URLs to psycopg-compatible.
      'postgresql+asyncpg://' → 'postgresql://'
      '?ssl=require' → '?sslmode=require'
    """
    if url.startswith("postgresql+"):
        url = "postgresql://" + url.split("postgresql+", 1)[1]
    if "?ssl=require" in url:
        url = url.replace("?ssl=require", "?sslmode=require")
    url = url.replace("postgresql://asyncpg://", "postgresql://")
    return url

def _effective_nouns_target(project_path: Path) -> Tuple[str, str]:
    """
    Determine whether we should use RDS (Postgres) or local SQLite.

    Returns (kind, target):
      - ("pg", DSN) if resolver returns a Postgres URI for object_sql_db
      - ("sqlite", /abs/path/to/nouns.db) otherwise
    """
    try:
        uri = get_db_uri("object_sql_db")
        debug("[dsn] resolver returned:", uri)
    except Exception as e:
        debug("[dsn] resolver failed:", repr(e))
        uri = None

    if uri and uri.startswith("postgresql"):
        return ("pg", _normalize_for_psycopg(uri))

    # fallback: local project SQLite path
    db_path = resolve_path(project_path, "object_sql_db")  # projects/<p>/nouns/sql/nouns.db
    return ("sqlite", db_path.as_posix())

class _DBHandle:
    def __init__(self, kind: str, conn):
        self.kind = kind  # "pg" or "sqlite"
        self.conn = conn

    def close(self):
        try:
            self.conn.close()
        except Exception:
            pass

@contextlib.contextmanager
def _open_db(project_path: Path) -> _DBHandle:
    kind, target = _effective_nouns_target(project_path)
    if kind == "pg" and _PSYCOPG_AVAILABLE:
        debug("[db] connect PG:", target)
        conn = psycopg.connect(target, autocommit=False)
        try:
            with conn.cursor() as cur:
                # keep us on public schema
                try:
                    cur.execute("SET search_path TO public;")
                except Exception:
                    pass
            yield _DBHandle("pg", conn)
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()
        return

    # SQLite fallback
    if kind == "pg" and not _PSYCOPG_AVAILABLE:
        debug("[db] psycopg missing; falling back to SQLite")

    db_path = resolve_path(project_path, "object_sql_db")
    db_path.parent.mkdir(parents=True, exist_ok=True)
    debug("[db] connect SQLite:", db_path)
    conn = sqlite3.connect(db_path.as_posix())
    conn.row_factory = sqlite3.Row
    try:
        conn.execute("PRAGMA foreign_keys=ON;")
        yield _DBHandle("sqlite", conn)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

# helpers for pg rows
def _fetchall_dicts_pg(cur) -> List[Dict[str, Any]]:
    cols = [c.name for c in cur.description]
    return [dict(zip(cols, row)) for row in cur.fetchall()]

def _fetchone_dict_pg(cur) -> Optional[Dict[str, Any]]:
    row = cur.fetchone()
    if row is None:
        return None
    cols = [c.name for c in cur.description]
    return dict(zip(cols, row))

# ──────────────────────────────────────────────────────────────────────────────
# Table name + schema helpers (RDS‐aware)
# ──────────────────────────────────────────────────────────────────────────────
_SANITIZE_RE = re.compile(r"[^0-9a-zA-Z_]")

def _sanitize_table_name(noun: str) -> str:
    base = _SANITIZE_RE.sub("_", noun).strip("_")
    if not base or not base[0].isalpha():
        base = f"T_{base}"
    return f"noun_{base}"

def _prefixed(project: str, noun_table: str) -> str:
    # noun_Sample -> <Project>_noun_Sample
    base = noun_table
    if base.startswith("noun_"):
        base = base[len("noun_"):]
    return f"{project}_noun_{base}"

def _ensure_table_sqlite(conn: sqlite3.Connection, noun_type: str, schema: dict) -> str:
    """Create table if missing; TEXT columns, PK=primary_id_field (SQLite only)."""
    table = _sanitize_table_name(noun_type)
    fields: dict = (schema or {}).get("fields", {})
    primary = schema.get("primary_id_field")

    columns = list(fields.keys())
    if primary and primary not in columns:
        columns.insert(0, primary)

    col_defs = []
    for c in columns:
        if c == primary:
            col_defs.append(f'"{c}" TEXT PRIMARY KEY')
        else:
            col_defs.append(f'"{c}" TEXT')

    sql = f'CREATE TABLE IF NOT EXISTS "{table}" ({", ".join(col_defs)})'
    debug("[sql][ensure_table]", sql)
    conn.execute(sql)
    conn.commit()
    return table

def _resolve_pg_table_and_primary(db: _DBHandle, project: str, noun_type: str, schema: dict) -> Tuple[str, str]:
    """
    Resolve the actual table name + primary column on RDS:
      1) try meta_tables(project, noun_name) → table_name, primary_id
      2) fallback to <project>_noun_<sanitized>, primary from schema
    """
    assert db.kind == "pg"
    primary = schema.get("primary_id_field") or "id"
    table_name = _prefixed(project, _sanitize_table_name(noun_type))

    with db.conn.cursor() as cur:
        try:
            cur.execute("""
                SELECT table_name, primary_id
                FROM meta_tables
                WHERE project = %s AND noun_name = %s
                LIMIT 1
            """, (project, noun_type))
            row = cur.fetchone()
            if row:
                tname, pid = row
                table_name = tname or table_name
                if pid:
                    primary = pid
        except Exception as e:
            debug("[pg] meta_tables lookup failed; fallback:", repr(e))

    return table_name, primary

# ──────────────────────────────────────────────────────────────────────────────
# Validation (RDS-aware for Reference lookups, DB-only)
# ──────────────────────────────────────────────────────────────────────────────
def _is_valid_date(val: str, fmt: str = "yyyy-mm-dd") -> bool:
    from datetime import datetime as _dt
    try:
        _dt.strptime(val.strip(), "%Y-%m-%d")
        return True
    except Exception:
        return False

def _list_ids_for_noun(project_path: Path, project: str, noun_name: str, pid_field: str) -> List[str]:
    """
    Return list of primary IDs for a noun, always from DB (RDS or SQLite).
    """
    schema = get_noun_schema(project_path, noun_name) or {}
    primary = pid_field or schema.get("primary_id_field") or "id"

    kind, _ = _effective_nouns_target(project_path)
    if kind == "pg" and _PSYCOPG_AVAILABLE:
        with _open_db(project_path) as db:
            table, primary_eff = _resolve_pg_table_and_primary(db, project, noun_name, schema)
            col = primary or primary_eff
            with db.conn.cursor() as cur:
                try:
                    cur.execute(f'SELECT "{col}" FROM "{table}"')
                    return [str(r[0]) for r in cur.fetchall() if r and r[0] is not None]
                except Exception as e:
                    debug("[pg] _list_ids_for_noun failed:", repr(e))
                    return []
    else:
        # SQLite
        dbp = resolve_path(project_path, "object_sql_db").as_posix()
        try:
            conn = sqlite3.connect(dbp)
            conn.row_factory = sqlite3.Row
            table = _ensure_table_sqlite(conn, noun_name, schema)
            cur = conn.execute(f'SELECT "{primary}" FROM "{table}"')
            return [str(r[0]) for r in cur.fetchall() if r and r[0] is not None]
        except Exception as e:
            debug("[sqlite] _list_ids_for_noun failed:", repr(e))
            return []
        finally:
            try:
                conn.close()
            except Exception:
                pass

def validate_item_against_schema(item: dict, noun_name: str, schema: dict, project_path: Path, project: Optional[str] = None) -> List[str]:
    """
    Validate a single item dict against the noun schema.
    - required fields
    - primitive types: date/number/string
    - adjective classes:
        * ActionRequirement: value ∈ request_options keys
        * Reference: value ∈ primary IDs of referenced noun
        * ReferenceList: all comma-separated values ∈ referenced noun IDs
    """
    errors: List[str] = []
    fields: dict = (schema or {}).get("fields", {})

    for field, f_schema in fields.items():
        raw = item.get(field, "")
        val = raw.strip() if isinstance(raw, str) else raw
        required = f_schema.get("required", False)
        ftype = f_schema.get("type")

        primary_field = (schema or {}).get("primary_id_field")

        if required and (val == "" or val is None):
            if field == primary_field:
                continue
            errors.append(f"'{field}' is required but missing.")
            continue
        if val in ("", None):
            continue

        if ftype == "date":
            fmt = f_schema.get("format", "yyyy-mm-dd")
            if not _is_valid_date(str(val), fmt):
                errors.append(f"'{field}' has invalid date '{val}' (expected {fmt}).")

        elif ftype == "number":
            try:
                float(val)
            except Exception:
                errors.append(f"'{field}' should be a number, got '{val}'.")

        elif ftype in ("string", "text"):
            if not isinstance(val, str):
                errors.append(f"'{field}' should be a string.")

        elif ftype == "adjective":
            adj = get_adjective_schema(project_path, field, applies_to=noun_name)
            if not adj:
                continue
            adj_class = (adj.get("class") or adj.get("adjective_class") or "").strip()

            if adj_class == "ActionRequirement":
                options = list((adj.get("request_options") or {}).keys())
                if str(val) not in options:
                    errors.append(f"'{field}' has invalid option '{val}' (must be one of {options}).")

            elif adj_class in {"Reference", "ReferenceList"}:
                ref_noun = adj.get("reference_noun")
                if not ref_noun:
                    errors.append(f"'{field}' missing reference_noun in adjective schema.")
                    continue
                ref_schema = get_noun_schema(project_path, ref_noun)
                if not ref_schema:
                    errors.append(f"'{field}' refers to unknown noun '{ref_noun}'.")
                    continue
                ref_primary = ref_schema.get("primary_id_field")
                if not ref_primary:
                    errors.append(f"'{field}' reference noun '{ref_noun}' lacks primary_id_field.")
                    continue

                valid_ids = set(_list_ids_for_noun(project_path, project or "", ref_noun, ref_primary))

                if adj_class == "Reference":
                    if str(val) not in valid_ids:
                        errors.append(f"'{field}' references unknown ID '{val}'.")
                else:
                    for part in str(val).split(","):
                        p = part.strip()
                        if p and p not in valid_ids:
                            errors.append(f"'{field}' contains unknown ID '{p}'.")

    return errors

