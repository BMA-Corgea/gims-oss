@router.post("/{project}/{noun_type}/create", summary="Create single instance")
def create_single(project: str, noun_type: str, payload: Dict[str, Any] = Body(...)):
    pp = get_project_path(project)
    schema = get_noun_schema(pp, noun_type)
    if not schema:
        raise HTTPException(404, f"Noun '{noun_type}' not found.")
    primary = schema.get("primary_id_field") or "id"

    # ---- validate
    errs: List[str] = []
    msg = _autogen_enforced_blank(schema, payload, mode="create")
    if msg:
        errs.append(msg)
    errs += validate_item_against_schema(payload, noun_type, schema, pp, project=project)
    if errs:
        return {"ok": False, "errors": errs}

    # ---- autogen primary if needed
    if schema.get("autogenerate_id") and not payload.get(primary):
        try:
            existing = _list_ids_for_noun(pp, project, noun_type, primary)
        except Exception:
            existing = []
        payload = {**payload, primary: _generate_primary(schema, noun_type, pp, existing)}

    kind, _ = _effective_nouns_target(pp)
    if kind == "pg" and _PSYCOPG_AVAILABLE:
        with _open_db(pp) as db:
            table, primary_eff = _resolve_pg_table_and_primary(db, project, noun_type, schema)
            try:
                clean_payload = {k: v for k, v in payload.items() if k.strip().lower() not in ('_rowid', 'rowid')}
                _insert_row_pg(db, table, clean_payload)
            except Exception as e:
                raise HTTPException(409, f"RDS insert failed: {e}")
    else:
        # SQLite
        dbp = resolve_path(pp, "object_sql_db").as_posix()
        try:
            conn = sqlite3.connect(dbp)
            conn.row_factory = sqlite3.Row
            table = _ensure_table_sqlite(conn, noun_type, schema)
            try:
                _insert_row_sqlite(conn, table, payload)
                conn.commit()
            except sqlite3.IntegrityError as e:
                raise HTTPException(409, f"Duplicate primary ID: {payload.get(primary)}") from e
        finally:
            try:
                conn.close()
            except Exception:
                pass

    return {"ok": True, "id": payload.get(primary)}

