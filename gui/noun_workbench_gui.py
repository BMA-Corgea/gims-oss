@router.get("/{project}/{noun_type}/references/{field_name}", summary="Dropdown options for Reference adjectives")
def get_reference_options(project: str, noun_type: str, field_name: str) -> List[Dict[str, str]]:
    pp = get_project_path(project)
    adj = get_adjective_schema(pp, field_name, applies_to=noun_type)
    if not adj:
        return []

    adj_class = adj.get("class") or adj.get("adjective_class")
    if adj_class not in {"Reference", "ReferenceList"}:
        return []

    ref_noun = adj.get("reference_noun") or adj.get("reference")
    if not ref_noun:
        return []

    ref_schema = get_noun_schema(pp, ref_noun) or {}
    ref_primary = ref_schema.get("primary_id_field") or "id"

    # DB-only
    kind, _ = _effective_nouns_target(pp)
    if kind == "pg" and _PSYCOPG_AVAILABLE:
        with _open_db(pp) as db:
            table, primary = _resolve_pg_table_and_primary(db, project, ref_noun, ref_schema)
            primary = ref_primary or primary
            with db.conn.cursor() as cur:
                try:
                    cur.execute(f'SELECT * FROM "{table}"')
                    rows = _fetchall_dicts_pg(cur)
                except Exception as e:
                    debug("[pg] get_reference_options error:", repr(e))
                    rows = []
        options: List[Dict[str, str]] = []
        for it in rows:
            val = it.get(primary)
            if not val:
                continue
            label = str(val)
            for cand in ["name", "label", "client", "description"]:
                if cand in it and it[cand] and cand != primary:
                    label = f"{val} — {it[cand]}"
                    break
            options.append({"value": str(val), "label": label})
        return options

    # SQLite
    dbp = resolve_path(pp, "object_sql_db").as_posix()
    try:
        conn = sqlite3.connect(dbp)
        conn.row_factory = sqlite3.Row
        table = _ensure_table_sqlite(conn, ref_noun, ref_schema)
        cur = conn.execute(f'SELECT * FROM "{table}"')
        rows = [dict(r) for r in cur.fetchall()]
    except Exception as e:
        debug("[sqlite] get_reference_options error:", repr(e))
        rows = []
    finally:
        try:
            conn.close()
        except Exception:
            pass

    options: List[Dict[str, str]] = []
    for it in rows:
        val = it.get(ref_primary)
        if not val:
            continue
        label = str(val)
        for cand in ["name", "label", "client", "description"]:
            if cand in it and it[cand] and cand != ref_primary:
                label = f"{val} — {it[cand]}"
                break
