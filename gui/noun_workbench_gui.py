@router.get("/{project}/{noun_type}/items", response_model=List[Dict[str, Any]])
def get_items(project: str, noun_type: str) -> List[Dict[str, Any]]:
    """
    Load all items for a given noun in a project, from DB only.
    RDS mode (Postgres): read from <project>_noun_<noun> table (resolve via meta_tables when available). 
    Offline (SQLite): read from project-local nouns.db.
    """
    proj_path = get_project_path(project)
    schema = get_noun_schema(proj_path, noun_type) or {}
    primary = schema.get("primary_id_field") or "id"

    kind, _ = _effective_nouns_target(proj_path)
    if kind == "pg" and _PSYCOPG_AVAILABLE:
        with _open_db(proj_path) as db:
            table, primary_eff = _resolve_pg_table_and_primary(db, project, noun_type, schema)
            with db.conn.cursor() as cur:
                try:
                    cur.execute(f'SELECT * FROM "{table}"')
                    rows = _fetchall_dicts_pg(cur)
                    def _clean_order(d: Dict[str, Any]) -> Dict[str, Any]:
                        if not isinstance(d, dict):
                            return d
                        r = dict(d)
                        r.pop(" rowid", None); r.pop("_rowid", None)
                        k1 = [primary_eff] if primary_eff in r else []
                        k2 = [k for k in r.keys()
                              if k not in k1 and not str(k).startswith("_") and k.strip().lower() != "rowid"]
                        k3 = [k for k in r.keys() if k not in k1 and k not in k2]
                        return {k: r.get(k) for k in (k1 + k2 + k3)}
                    return [_clean_order(x) for x in rows]
                except Exception as e:
                    raise HTTPException(status_code=500, detail=f"RDS read failed for {noun_type}: {e}")
    else:
        # SQLite
        dbp = resolve_path(proj_path, "object_sql_db").as_posix()
        try:
            conn = sqlite3.connect(dbp)
            conn.row_factory = sqlite3.Row
            table = _ensure_table_sqlite(conn, noun_type, schema)
            cur = conn.execute(f'SELECT * FROM "{table}"')
            rows = [dict(r) for r in cur.fetchall()]
        except Exception as e:
            raise HTTPException(status_code=500, detail=f"SQLite read failed for {noun_type}: {e}")
        finally:
            try:
                conn.close()
            except Exception:
                pass

        def _clean_order(d: Dict[str, Any]) -> Dict[str, Any]:
            if not isinstance(d, dict):
                return d
            r = dict(d)
            r.pop(" rowid", None); r.pop("_rowid", None)
            k1 = [primary] if primary in r else []
            k2 = [k for k in r.keys()
                  if k not in k1 and not str(k).startswith("_") and k.strip().lower() != "rowid"]
            k3 = [k for k in r.keys() if k not in k1 and k not in k2]
            return {k: r.get(k) for k in (k1 + k2 + k3)}
        return [_clean_order(x) for x in rows]

