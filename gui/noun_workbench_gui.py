# Insert/Update helpers

def _insert_row_sqlite(conn: sqlite3.Connection, table: str, row: Dict[str, Any]):
    cols = list(row.keys())
    ph   = ", ".join(["?"] * len(cols))
    col_names = ", ".join([f'"{c}"' for c in cols])
    sql = f'INSERT INTO "{table}" ({col_names}) VALUES ({ph})'
    debug("[sql][insert]", sql, row)
    conn.execute(sql, tuple(None if v == "" else v for v in row.values()))

def _update_row_sqlite(conn: sqlite3.Connection, table: str, primary_field: str, primary_val: str, row: Dict[str, Any]):
    set_cols = [c for c in row.keys() if c != primary_field]
    if not set_cols:
        return
    assigns = ", ".join([f'"{c}"=?' for c in set_cols])
    sql = f'UPDATE "{table}" SET {assigns} WHERE "{primary_field}"=?'
    args = [None if row[c] == "" else row[c] for c in set_cols] + [primary_val]
    debug("[sql][update]", sql, args)
    conn.execute(sql, tuple(args))

def _insert_row_pg(db: _DBHandle, table: str, row: Dict[str, Any]):
    """
    Insert a row into a Postgres noun table.
    - Never manually insert _rowid (auto-generated identity)
    - Cleans empty strings → NULL
    """
    # Drop _rowid if present — Postgres will auto-generate it (case-insensitive)
    row = {k: v for k, v in row.items() if k.strip().lower() not in ('_rowid', 'rowid')}

    if not row:
        return  # nothing to insert (shouldn't happen)

    cols = list(row.keys())
    placeholders = ", ".join(["%s"] * len(cols))
    col_names = ", ".join([f'"{c}"' for c in cols])
    sql = f'INSERT INTO "{table}" ({col_names}) VALUES ({placeholders})'

    vals = [None if v == "" else v for v in row.values()]
    debug("[pg][insert]", sql, vals)
    with db.conn.cursor() as cur:
        cur.execute(sql, vals)

def _update_row_pg(db: _DBHandle, table: str, primary_field: str, primary_val: str, row: Dict[str, Any]):
    """
    Update an existing Postgres row by primary key.
    - Never updates _rowid
    """
    # Case-insensitive filtering for _rowid variants
    row = {k: v for k, v in row.items() 
           if k.strip() not in (primary_field,) and k.strip().lower() not in ('_rowid', 'rowid')}
    if not row:
        return
    assigns = ", ".join([f'"{c}"=%s' for c in row])
    sql = f'UPDATE "{table}" SET {assigns} WHERE "{primary_field}"=%s'
    vals = [None if row[c] == "" else row[c] for c in row] + [primary_val]
    debug("[pg][update]", sql, vals)
    with db.conn.cursor() as cur:
        cur.execute(sql, vals)

def _exists_by_primary_pg(db: _DBHandle, table: str, primary_field: str, primary_val: str) -> bool:
    with db.conn.cursor() as cur:
        cur.execute(f'SELECT 1 FROM "{table}" WHERE "{primary_field}"=%s LIMIT 1', (primary_val,))
        return cur.fetchone() is not None

