@router.post("/{project}/{noun_type}/bulk_commit", summary="Commit previewed rows to DB (no JSONL)")
def bulk_commit(
    project: str,
    noun_type: str,
    mode: str = "create",
    storage_backend: str = "sql",  # enforced
    rows: Dict[str, Any] = Body(...)
):
    """
    Expects body: { "rows": [ { ...payload... }, ... ] }
    
    mode:
      - create: add new items
      - update: replace existing items by primary
      - upsert: replace if exists else add

    storage_backend:
      - sql: only write to SQL database (enforced)
    """
    if storage_backend != "sql":
        raise HTTPException(400, "storage_backend must be 'sql' (JSONL disabled for nouns).")

    pp = get_project_path(project)
    schema = get_noun_schema(pp, noun_type)
    if not schema:
        raise HTTPException(404, f"Noun '{noun_type}' not found.")

    payloads = rows.get("rows") or []
    if not isinstance(payloads, list):
        raise HTTPException(400, "Body must contain a 'rows' list.")

    primary = schema.get("primary_id_field") or "id"
    inserted = 0
    updated = 0
    skipped = 0
    errors: List[str] = []

    kind, _ = _effective_nouns_target(pp)
    if kind == "pg" and _PSYCOPG_AVAILABLE:
        with _open_db(pp) as db:
            table, primary_eff = _resolve_pg_table_and_primary(db, project, noun_type, schema)

            for i, raw in enumerate(payloads, start=1):
                msg = _autogen_enforced_blank(schema, raw, mode)
                errs = [msg] if msg else []
                if mode in ("update", "upsert") and not raw.get(primary):
                    if not (mode == "upsert" and schema.get("autogenerate_id")):
                        errs.append(f"Primary field '{primary}' is required for {mode} mode.")
                errs += validate_item_against_schema(raw, noun_type, schema, pp, project=project)

                if errs:
                    skipped += 1
                    errors.append(f"Row {i}: " + "; ".join(errs))
                    continue

                pid = raw.get(primary)

                if (mode in ("update", "upsert")) and pid and _exists_by_primary_pg(db, table, primary_eff, pid):
                    try:
                        _update_row_pg(db, table, primary_eff, pid, raw)
                        updated += 1
                    except Exception as e:
                        skipped += 1
                        errors.append(f"Row {i}: update error '{pid}' ({e})")
                else:
                    if mode == "create" or (mode == "upsert"):
                        if schema.get("autogenerate_id") and not pid:
                            try:
                                existing = _list_ids_for_noun(pp, project, noun_type, primary)
                            except Exception:
                                existing = []
                            raw = {**raw, primary: _generate_primary(schema, noun_type, pp, existing)}
                        try:
                            _insert_row_pg(db, table, raw)
                            inserted += 1
                        except Exception as e:
                            skipped += 1
                            errors.append(f"Row {i}: insert error '{raw.get(primary)}' ({e})")
                    else:
                        skipped += 1
                        errors.append(f"Row {i}: '{raw.get(primary)}' not found for update")
    else:
        # SQLite
        dbp = resolve_path(pp, "object_sql_db").as_posix()
        try:
            conn = sqlite3.connect(dbp)
            conn.row_factory = sqlite3.Row
            table = _ensure_table_sqlite(conn, noun_type, schema)

            def _exists(pid: str) -> bool:
                cur = conn.execute(f'SELECT 1 FROM "{table}" WHERE "{primary}"=?', (pid,))
                return cur.fetchone() is not None

            for i, raw in enumerate(payloads, start=1):
                msg = _autogen_enforced_blank(schema, raw, mode)
                errs = [msg] if msg else []
                if mode in ("update", "upsert") and not raw.get(primary):
                    if not (mode == "upsert" and schema.get("autogenerate_id")):
                        errs.append(f"Primary field '{primary}' is required for {mode} mode.")
                errs += validate_item_against_schema(raw, noun_type, schema, pp, project=project)

                if errs:
                    skipped += 1
                    errors.append(f"Row {i}: " + "; ".join(errs))
                    continue

                if mode == "create":
                    try:
                        _insert_row_sqlite(conn, table, raw)
                        inserted += 1
                    except sqlite3.IntegrityError:
                        skipped += 1
                        errors.append(f"Row {i}: duplicate '{raw.get(primary)}'")

                elif mode == "update":
                    if not _exists(raw.get(primary)):
                        skipped += 1
                        errors.append(f"Row {i}: '{raw.get(primary)}' not found for update")
                    else:
                        _update_row_sqlite(conn, table, primary, raw.get(primary), raw)
                        updated += 1
                else:  # upsert
                    pid = raw.get(primary)
                    if pid and _exists(pid):
                        _update_row_sqlite(conn, table, primary, pid, raw)
                        updated += 1
                    else:
                        if schema.get("autogenerate_id") and not pid:
                            try:
                                existing = _list_ids_for_noun(pp, project, noun_type, primary)
                            except Exception:
                                existing = []
                            raw = {**raw, primary: _generate_primary(schema, noun_type, pp, existing)}
                            pid = raw.get(primary)
                        try:
                            _insert_row_sqlite(conn, table, raw)
                            inserted += 1
                        except sqlite3.IntegrityError:
                            skipped += 1
                            errors.append(f"Row {i}: conflict on '{raw.get(primary)}'")
            conn.commit()
        finally:
            try:
                conn.close()
            except Exception:
                pass

    return {
        "inserted": inserted, 
        "updated": updated, 
        "skipped": skipped, 
        "errors": errors,
        "storage_backend": "sql"
    }