def test_generate_date_segment_valid():
    seg = ig.generate_date_segment("mmddyyyy")
    assert len(seg) == 8


def test_generate_date_segment_invalid():
    assert ig.generate_date_segment("invalid") == "invalid"


def test_generate_hex_segment():
    assert ig.generate_hex_segment(0x10, 1, 4) == "0011"


def test_generate_autogenerated_id(tmp_path):
    schema = {
        "autogenerate_segments": [
            {"type": "static", "value": "S"},
            {"type": "number", "length": 3}
        ]
    }
    counters = tmp_path / "autogen_counters.json"
    noun_types = tmp_path / "noun_types.json"
    noun_types.write_text("{}")
    result = ig.generate_autogenerated_id("Sample", schema, noun_types, set())
    assert result.startswith("S")
    data = json.loads(counters.read_text())
    assert data["Sample"]["S"] == 0

