def test_generate_autogenerated_id_full_prefix(tmp_path):
    schema = {
        "autogenerate_segments": [
            {"type": "static", "value": "X"},
            {"type": "static", "value": "Y"},
            {"type": "date", "format": "yy"},
            {"type": "number", "length": 2}
        ]
    }
    noun_types = tmp_path / "noun_types.json"
    noun_types.write_text("{}")
    result = ig.generate_autogenerated_id("N", schema, noun_types, set())
    # The prefix should include "XY" followed by the two-digit year
    expected_prefix = "XY" + datetime.datetime.now().strftime("%y")
    assert result.startswith(expected_prefix)

