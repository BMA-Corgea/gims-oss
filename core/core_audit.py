# Adjective ↔ Noun type alignment (schema level)
# -------------------------------

def audit_adjective_alignment(
    noun_types: NounTypes,
    adjective_types: AdjectiveTypes
) -> List[Finding]:
    debug("[audit_adjective_alignment] Start")
    findings: List[Finding] = []

    # Build a lookup of adjective name -> class
    adj_classes = {name: (d.get("adjective_class") or d.get("class") or "").lower()
                   for name, d in adjective_types.items()}
    debug("[audit_adjective_alignment] adj_classes:", adj_classes)

    for nt_name, nt_schema in noun_types.items():
        adj_fields: Dict[str, Dict[str, Any]] = nt_schema.get("adjective_fields", {}) or {}
        debug(f"[audit_adjective_alignment] noun_type={nt_name} fields={list(adj_fields.keys())}")
        for field, cfg in adj_fields.items():
            declared_class = (cfg.get("adjective_class") or cfg.get("class") or "").lower()
            adj_name = cfg.get("adjective") or field  # if you store by name, keep this flexible
            if adj_name in adjective_types:
                real_class = adj_classes.get(adj_name, "")
                if declared_class and real_class and declared_class != real_class:
                    debug(f"[audit_adjective_alignment] Class mismatch noun_type={nt_name} field={field} declared={declared_class} actual={real_class}")
                    findings.append(Finding(
                        code="ADJ_CLASS_MISMATCH",
                        severity="error",
                        where={"scope": "noun_type", "noun_type": nt_name, "field": field, "adjective": adj_name},
                        message=f"Adjective class mismatch: {declared_class} vs {real_class}",
                        details={"declared": declared_class, "actual": real_class}
                    ))
            else:
                debug(f"[audit_adjective_alignment] Unknown adjective type noun_type={nt_name} field={field} adj={adj_name}")
                findings.append(Finding(
                    code="ADJ_TYPE_UNKNOWN",
                    severity="error",
                    where={"scope": "noun_type", "noun_type": nt_name, "field": field, "adjective": adj_name},
                    message=f"Unknown adjective type '{adj_name}' referenced by noun type '{nt_name}'",
                    details={}
                ))

    debug("[audit_adjective_alignment] Done -> findings:", len(findings))
    return findings


# -------------------------------
# Orchestration entrypoints
# -------------------------------

def audit_all(
    *,
    noun_types: NounTypes,
    verb_types: VerbTypes,
    adverb_types: AdverbTypes,
    adjective_types: AdjectiveTypes,
    noun_instances_by_type: NounInstancesByType,
    run_entries_by_group: RunEntriesByGroup,
    noun_index: Optional[NounIndex] = None,
    override_index: Optional[OverrideIndex] = None,
) -> Dict[str, Any]:
    """
    Perform all instance-level audits (no filesystem, no interpretation).
    Returns a dict with `findings` (list of Finding as dict) and `summary`.
    """
    debug("[audit_all] Start")
    # Build noun_index if not provided
    if noun_index is None:
        debug("[audit_all] Building noun_index from noun_instances_by_type")
        noun_index = {
            k: {
                inst.get(noun_types.get(k, {}).get("primary_id_field"))
                for inst in v
                if inst.get(noun_types.get(k, {}).get("primary_id_field"))
            }
            for k, v in noun_instances_by_type.items()
        }
    debug("[audit_all] noun_index keys:", {k: len(v) for k, v in noun_index.items()})
    override_index = override_index or {}
    debug("[audit_all] override_index keys:", list(override_index.keys()))

    findings: List[Finding] = []

    # Nouns
    n_findings = audit_noun_instances(noun_types, noun_instances_by_type, noun_index)
    findings += n_findings
    debug("[audit_all] Noun findings:", len(n_findings))

    # Adverbs vs Verbs
    adv_type_findings = audit_adverb_type_alignment(adverb_types, verb_types, noun_types)
    findings += adv_type_findings
    debug("[audit_all] Adverb-type findings:", len(adv_type_findings))

    # Adjectives vs Nouns
    adj_findings = audit_adjective_alignment(noun_types, adjective_types)
    findings += adj_findings
    debug("[audit_all] Adjective findings:", len(adj_findings))

    # Runs
    run_findings = audit_run_entries(run_entries_by_group, verb_types, noun_types, adverb_types, noun_index, override_index)
    findings += run_findings
    debug("[audit_all] Run findings:", len(run_findings))

    # Convert to serializable output
    as_dicts = [asdict(f) for f in findings]
    summary = summarize_findings(findings)
    debug("[audit_all] Done. Total findings:", len(as_dicts))
    return {
        "findings": as_dicts,
        "summary": summary,
    }


